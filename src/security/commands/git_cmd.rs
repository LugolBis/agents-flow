//! Hardened Git path.
//!
//! - **Subcommand validation**: Rejects any global options (`-c`, `-C`,
//!   `--git-dir`, etc.) and requires a subcommand present in `GIT_READ_SPECS`.
//! - **Execution**: Delegates to `GitReader::run_read` (the `argv` is constructed
//!   by the reader; no shell, no composition).
//! - **Validation without execution**: Produces the canonical `argv` via `GitReader::argv_for`
//!   (for tests, dry-runs, etc.).
//!
//! Checking whether Git is unavailable is the responsibility of the caller
//! (`policy::CommandPolicy`), which holds the `Option<Arc<GitReader>>`.
use super::output::CommandOutput;
use crate::error::{SecResult, SecurityError};
use crate::security::git_guard::{core::GIT_READ_SPECS, reader::GitReader};

use std::path::Path;

/// Vérifie que `tokens[0]` est une sous-commande git autorisée et non une option
/// globale. `tokens` doit être non vide (garanti par `policy::parse`).
pub(super) fn check_sub(tokens: &[String]) -> SecResult<()> {
    let first = tokens
        .first()
        .ok_or_else(|| SecurityError::command("missing_argument", "git: sub command required"))?;

    if first.starts_with('-') {
        return Err(SecurityError::command(
            "flag_not_allowed",
            "git: forbidden global options (-c, -C, --git-dir…)",
        ));
    }

    if !GIT_READ_SPECS.contains_key(first.as_str()) {
        return Err(SecurityError::command(
            "git_subcommand_not_allowed",
            format!(
                "unauthorized sub command : {}",
                crate::util::clip(first, 20)
            ),
        ));
    }

    Ok(())
}

/// Executes a **read-only** Git command in `base` and packages the output.
///
/// The `[output truncated]` marker is generated by `GitReader`; it is propagated
/// to `truncated` to maintain consistency with `CommandPolicy::run`.
pub(super) fn run(git: &GitReader, base: &Path, tokens: &[String]) -> SecResult<CommandOutput> {
    check_sub(tokens)?;

    let repo = git.open(&base.to_string_lossy())?;
    let text = git.run_read(&repo, &tokens[0], &tokens[1..])?;

    Ok(CommandOutput {
        truncated: text.ends_with("[truncated output]"),
        text,
        exit_code: 0,
        timed_out: false,
    })
}

/// Produces the canonical `argv` **without executing**, prefixed with `"git"`.
/// Used by `CommandPolicy::validate` and by integration tests.
pub(super) fn validate(git: &GitReader, base: &Path, tokens: &[String]) -> SecResult<Vec<String>> {
    check_sub(tokens)?;
    let repo = git.open(&base.to_string_lossy())?;

    let mut vec = vec!["git".to_string()];
    vec.extend(git.argv_for(&repo, &tokens[0], &tokens[1..])?);

    Ok(vec)
}
